const express = require('express')
const controller = require('../controllers/adminController')
const { allowRoles, protect } = require('../middleware/auth')
const databaseRequired = require('../middleware/databaseRequired')

const router = express.Router()
router.use(databaseRequired, protect, allowRoles('admin'))
router.get('/dashboard', controller.dashboard)
router.get('/customers', controller.listCustomers)
router.patch('/customers/:customerId', controller.updateCustomer)
router.get('/products', controller.listProducts)
router.post('/products', controller.createProduct)
router.patch('/products/:productId', controller.updateProduct)
router.delete('/products/:productId', controller.archiveProduct)
router.patch('/inventory/:productId', controller.updateInventory)
router.get('/categories', controller.listCategories)
router.post('/categories', controller.createCategory)
router.patch('/categories/:categoryId', controller.updateCategory)
router.get('/orders', controller.listOrders)
router.patch('/orders/:orderId/decision', controller.decideOrder)
router.patch('/orders/:orderId/status', controller.updateOrderStatus)
router.get('/payments', controller.listPayments)
router.patch('/payments/:orderId/decision', controller.decidePayment)
router.get('/reviews', controller.listReviews)
router.patch('/reviews/:reviewId', controller.moderateReview)

module.exports = router